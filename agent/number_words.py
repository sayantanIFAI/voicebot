_DROP = str.maketrans("", "", "ँं़ঁ়")  # chandrabindu, anusvara, nukta (Devanagari and Bengali)


def _loose(word: str) -> str:
    return unicodedata.normalize("NFC", word).translate(_DROP).replace("‌", "").replace("‍", "")


TWO_DIGIT: dict[str, str] = {}
for _i, _w in enumerate(_BN):
    TWO_DIGIT[_loose(_w)] = str(10 + _i)
for _i, _w in enumerate(_HI):
    TWO_DIGIT[_loose(_w)] = str(10 + _i)
for _w, _n in {**_BN_EXTRA, **_HI_EXTRA}.items():
    TWO_DIGIT[_loose(_w)] = str(_n)


def digits_of(token: str) -> str | None:
    """"আটানব্বই" -> "98", "चौहत्तर" -> "74"; None when the token is not one of these numbers."""
    return TWO_DIGIT.get(_loose(token or ""))
